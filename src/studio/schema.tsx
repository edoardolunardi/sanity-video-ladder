"use client";

import { defineArrayMember, defineField, defineType, type ObjectInputProps } from "sanity";
import { friendlyNameFromUrl } from "../core/layout.ts";
import { type VideoLadderConfig, VideoLadderProvider } from "./config.tsx";
import { VideoInput } from "./input/video-input.tsx";

// The stored video. Everything lives in `renditions[]` (the untouched original is just a rendition, not a
// special top-level url) and each rendition carries its own sized poster; the site paints the top-level
// `placeholder` blur. Field names, the `rendition` member and its `_key`s are a contract with existing
// documents.

export function createVideoType(config: VideoLadderConfig) {
  function Input(props: ObjectInputProps<Record<string, unknown>>) {
    return (
      <VideoLadderProvider config={config}>
        <VideoInput {...props} />
      </VideoLadderProvider>
    );
  }

  const qualities = [
    { title: "Original", value: "original" },
    ...[...config.tiers].reverse().map((tier) => ({ title: `${tier}p`, value: `${tier}` })),
  ];

  return defineType({
    name: config.typeName,
    title: "Video",
    type: "object",
    components: { input: Input },
    fields: [
      defineField({
        name: "renditions",
        title: "Renditions",
        type: "array",
        description:
          "Quality ladder generated by the uploader (the original plus each rung), each with its own poster. The site picks the right one per context. Auto-filled on upload.",
        // The "upload completed" gate: publishable only once a rendition exists. Skipped while the video object
        // itself does not exist yet, so a hidden or unused video field carries no permanent error; the
        // surrounding field's own required rule covers that case.
        validation: (rule) =>
          rule.custom((renditions, { parent }) => {
            if (!parent) {
              return true;
            }

            return Array.isArray(renditions) && renditions.length > 0
              ? true
              : "Upload and process a video before publishing (no renditions generated yet).";
          }),
        of: [
          defineArrayMember({
            type: "object",
            name: "rendition",
            fields: [
              defineField({
                name: "quality",
                type: "string",
                options: { layout: "radio", direction: "horizontal", list: qualities },
                validation: (rule) => rule.required(),
              }),
              defineField({ name: "url", type: "url" }),
              defineField({ name: "poster", type: "url", description: "This rendition's own poster." }),
            ],
            preview: {
              select: { quality: "quality", url: "url", poster: "poster" },
              prepare: ({ quality, url, poster }) => ({
                title: quality === "original" ? "Original" : quality ? `${quality}p` : "Rendition",
                subtitle: typeof url === "string" ? url : undefined,
                media: typeof poster === "string" ? <img src={poster} alt="" /> : undefined,
              }),
            },
          }),
        ],
      }),
      ...(config.playback
        ? [
            defineField({
              name: "playback",
              title: "Playback",
              type: "object",
              description:
                "How the clip plays on the site. Defaults suit a silent background loop; turn on controls for a video meant to be watched.",
              options: { columns: 2, collapsible: true, collapsed: false },
              fields: [
                defineField({ name: "autoplay", title: "Autoplay", type: "boolean", initialValue: true }),
                defineField({ name: "muted", title: "Muted", type: "boolean", initialValue: true }),
                defineField({ name: "loop", title: "Loop", type: "boolean", initialValue: true }),
                defineField({ name: "controls", title: "Controls", type: "boolean", initialValue: false }),
              ],
            }),
          ]
        : []),
      defineField({
        name: "placeholder",
        title: "Blur placeholder (auto)",
        type: "text",
        rows: 2,
        description: "Base64 blur painted while the video loads. Auto-filled on upload.",
      }),
      defineField({
        name: "dimensions",
        type: "object",
        description: "Auto-filled on upload. Drives the aspect ratio and reserves layout space.",
        options: { columns: 2, collapsed: false, collapsible: false },
        fields: [
          defineField({ name: "width", type: "number", validation: (rule) => rule.required() }),
          defineField({ name: "height", type: "number", validation: (rule) => rule.required() }),
        ],
      }),
    ],
    preview: {
      select: { renditions: "renditions" },
      prepare: ({ renditions }) => {
        const list = Array.isArray(renditions) ? renditions : [];
        const original = list.find((r) => r?.quality === "original") ?? list[0];
        const url = typeof original?.url === "string" ? original.url : "";
        return {
          // The folder name, so a breadcrumb reads "glyph field 0" instead of a raw bucket URL.
          title: friendlyNameFromUrl(url) || "Video",
          subtitle: list.length ? `${list.length} rendition(s)` : "empty",
          media: typeof original?.poster === "string" ? <img src={original.poster} alt="" /> : undefined,
        };
      },
    },
  });
}
